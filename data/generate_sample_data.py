"""Creates DETERMINISTIC SYNTHETIC business listings (same output every run).

Outputs (in this folder):
  sample_listings.csv           -> for the /api/listings/upload-csv endpoint
  business_listings_db_dump.sql -> schema + INSERTs, run it in MySQL Workbench

!! ALL RECORDS ARE FAKE. Names, addresses and phone numbers are randomly generated.
!! Every row's `source` starts with "Synthetic" so they can never be mistaken for real data.

Run:  python generate_sample_data.py
"""
import csv
import random
from datetime import datetime, timedelta
from pathlib import Path

SEED = 42
TOTAL = 650
HERE = Path(__file__).resolve().parent

CITIES = {"Mumbai": 16, "Delhi": 14, "Bengaluru": 13, "Pune": 10, "Hyderabad": 9, "Chennai": 8,
          "Kolkata": 7, "Ahmedabad": 6, "Jaipur": 4, "Lucknow": 3, "Nagpur": 3, "Surat": 3,
          "Indore": 2, "Kochi": 2}  # weights, so the bar chart looks realistic

CATEGORIES = {
    "Restaurant": ["Kitchen", "Dining", "Bistro", "Tiffin House"],
    "Cafe": ["Cafe", "Coffee Roasters", "Brew Bar"],
    "Grocery Store": ["Fresh Mart", "Supermarket", "Kirana Store"],
    "Pharmacy": ["Medicals", "Pharmacy", "Chemist"],
    "Clothing Store": ["Fashions", "Boutique", "Garments"],
    "Electronics Shop": ["Electronics", "Digital Hub", "Mobile Point"],
    "Gym & Fitness": ["Fitness Club", "Gym", "Yoga Studio"],
    "Salon & Spa": ["Salon", "Beauty Studio", "Spa"],
    "Hospital & Clinic": ["Clinic", "Care Centre", "Diagnostics"],
    "Education & Coaching": ["Academy", "Coaching Classes", "Learning Hub"],
    "Automobile Service": ["Auto Care", "Motors", "Garage"],
    "Hotel": ["Residency", "Inn", "Suites"],
}
PREFIXES = ["Sharma", "Patel", "Royal", "Sunrise", "Green Leaf", "Blue Moon", "Annapurna", "Gupta",
            "Lotus", "Metro", "City Star", "Krishna", "Raj", "Silver Oak", "Modern", "Prime", "Urban",
            "Golden", "Reddy", "Iyer", "Khan", "Singh", "Mehta", "Nova", "Classic", "Everest",
            "Orchid", "Sai", "Ganesh", "Paradise"]
STREETS = ["MG Road", "Station Road", "Gandhi Marg", "Nehru Street", "Market Road", "Temple Road",
           "Park Avenue", "Lake View Road", "Main Bazaar", "Ring Road", "College Road", "Hill Road"]
AREAS = ["Central Area", "North Zone", "South Zone", "East End", "West End", "Old Town", "New Town",
         "Civil Lines", "Industrial Area", "Residency Layout"]
SOURCES = {"Synthetic - Online Directory Style": 35, "Synthetic - Maps Style": 30,
           "Synthetic - Survey Style": 20, "Synthetic - Referral Style": 15}


def build_rows():
    rng = random.Random(SEED)
    cities, city_w = zip(*CITIES.items())
    sources, source_w = zip(*SOURCES.items())
    categories = list(CATEGORIES)
    base = datetime(2026, 1, 1, 9, 0, 0)
    used_phones, rows = set(), []
    for i in range(TOTAL):
        category = rng.choice(categories)
        city = rng.choices(cities, weights=city_w)[0]
        while True:
            digits = rng.choice("6789") + "".join(rng.choice("0123456789") for _ in range(9))
            phone = f"+91 {digits[:5]} {digits[5:]}"
            if phone not in used_phones:
                used_phones.add(phone)
                break
        rows.append({
            "id": i + 1,
            "business_name": f"{rng.choice(PREFIXES)} {rng.choice(CATEGORIES[category])}",
            "category": category,
            "city": city,
            "address": f"{rng.randint(1, 250)}, {rng.choice(STREETS)}, {rng.choice(AREAS)}, {city}",
            "phone": phone,
            "source": rng.choices(sources, weights=source_w)[0],
            "created_at": (base + timedelta(hours=i * 6, minutes=rng.randint(0, 59))).strftime("%Y-%m-%d %H:%M:%S"),
        })
    return rows


def sql_text(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def main():
    rows = build_rows()

    with open(HERE / "sample_listings.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=["business_name", "category", "city", "address", "phone", "source"],
                           extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)

    schema = (HERE / "schema.sql").read_text(encoding="utf-8")
    cols = "(id, business_name, category, city, address, phone, source, created_at)"
    with open(HERE / "business_listings_db_dump.sql", "w", encoding="utf-8", newline="\n") as f:
        f.write("-- MySQL dump: business_listings_db (SYNTHETIC SAMPLE DATA - not real businesses)\n")
        f.write(f"-- Records: {len(rows)} | Generated by generate_sample_data.py | seed={SEED}\n\n")
        f.write("SET NAMES utf8mb4;\n\n" + schema + "\nTRUNCATE TABLE listing_master;\n\n")
        for start in range(0, len(rows), 100):
            chunk = rows[start:start + 100]
            values = ",\n".join(
                "  (" + ", ".join([str(r["id"])] + [sql_text(r[k]) for k in
                 ("business_name", "category", "city", "address", "phone", "source", "created_at")]) + ")"
                for r in chunk)
            f.write(f"INSERT INTO listing_master {cols} VALUES\n{values};\n\n")
    print(f"Done: {len(rows)} synthetic records written.")


if __name__ == "__main__":
    main()
